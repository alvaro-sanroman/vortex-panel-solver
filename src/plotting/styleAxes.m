function styleAxes(ax, T)
%STYLEAXES  Apply the project's dark theme to an axes object.
%   styleAxes(ax)      uses plotTheme()
%   styleAxes(ax, T)   uses a theme struct you already loaded

    if nargin < 2, T = plotTheme(); end

    set(ax, 'Color',     T.bg, ...
            'XColor',    T.fg, ...
            'YColor',    T.fg, ...
            'GridColor', T.grid, ...
            'GridAlpha', 0.5, ...
            'FontName',  T.font, ...
            'FontSize',  11, ...
            'LineWidth', 0.8, ...
            'Box',       'on', ...
            'TickDir',   'out');
    grid(ax, 'on');
    ax.Title.Color      = T.fg;
    ax.Title.FontWeight = 'normal';
    ax.Title.FontSize   = 13;
end